// These run REAL cargo over a real crate through the pool's own validator and
// scorer, the way certify --repo will on Warp: the Declared landing is
// derived by the door's own call (lang.TestLanding over
// reposcan.DiskSources), the writer's body is landed by ParseTest, compiled
// by CompileTest, and graded by ScoreAuthoredReport against a mutant of a
// PRIVATE function — under `cargo test` and `cargo nextest run`, in the bwrap
// jail and on the workspace substrate (a checkout mutated in place and
// restored). cgo-only: the landing reads the source's `mod` declaration with
// the tree-sitter grammar.
//
// Every skip message starts with SKIP: because CI greps the -v output for
// it: a jail test that skips silently proves nothing about the landing.

const systemCargoBin = "/usr/local/cargo/bin"

// crate is a Warp-shaped crate: src/foo.rs declares its tests in a separate
// file with #[path], and the private fn is what the mutant breaks.
var crate = map[string]string{
	"Cargo.toml": "[package]\nname = \"landing_fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\n",
	"Cargo.lock": "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"landing_fixture\"\nversion = \"0.1.0\"\n",
	"src/lib.rs": "pub mod foo;\n",
	"src/foo.rs": "fn private_double(x: i32) -> i32 {\n    x * 2\n}\n\npub fn quadruple(x: i32) -> i32 {\n    private_double(private_double(x))\n}\n\n#[cfg(test)]\n#[path = \"foo_tests.rs\"]\nmod tests;\n",
	// The project's own test: it never reaches private_double's value on its
	// own, so the mutant below survives it and only the authored test kills.
	"src/foo_tests.rs": "use super::*;\n\n#[test]\nfn quadruple_of_zero() {\n    assert_eq!(quadruple(0), 0);\n}\n",
}

// writerBody is what a test-writer returns: test items only, no wrapper.
const writerBody = "#[test]\nfn test_private_double_doubles() {\n    assert_eq!(private_double(21), 42);\n}"

func rustToolchainOrSkip(t *testing.T) {
	t.Helper()
	if _, err := os.Stat("/usr/local/rustup/toolchains"); err != nil {
		t.Skipf("SKIP: no system-wide rustup at /usr/local/rustup (scripts/ci-provision-test-toolchains.sh installs it): %v", err)
	}
	if _, err := os.Stat(systemCargoBin + "/cargo-nextest"); err != nil {
		t.Skipf("SKIP: no cargo-nextest in %s: %v", systemCargoBin, err)
	}
	t.Setenv("PATH", systemCargoBin+":"+os.Getenv("PATH"))
	t.Setenv("RUSTUP_HOME", "/usr/local/rustup")
}

func writeCrate(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	for rel, body := range crate {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// landingFor is the door's own derivation, converted to the workspace key
// the way certify --local's wiring converts it (the crate root IS the repo).
func landingFor(t *testing.T, dir string) advpool.AuthoredLanding {
	t.Helper()
	p, _ := lang.ByName("rust")
	l, err := lang.TestLanding("src/foo.rs", reposcan.DiskSources(p, dir))
	if err != nil {
		t.Fatal(err)
	}
	if err := lang.CheckTestLanding("src/foo.rs", l); err != nil {
		t.Fatalf("the door refuses the fixture: %v", err)
	}
	if l.Path != "src/foo_tests.rs" || !l.Into || l.Depth != 1 {
		t.Fatalf("landing = %+v, want the declared src/foo_tests.rs at depth 1", l)
	}
	return advpool.AuthoredLanding{Landing: l, Existing: crate["src/foo_tests.rs"]}
}

func gradeTheLanding(t *testing.T, jail adequacy.Jail, base map[string]string, landing advpool.AuthoredLanding, testCmd string) {
	t.Helper()
	ctx := context.Background()
	v := advpool.JailValidator{Jail: jail, BaseFiles: base, DevTestPath: "src/foo_tests.rs", Landing: landing}
	s := advpool.JailScorer{Jail: jail, BaseFiles: base, DevTestPath: "src/foo_tests.rs", Landing: landing}

	test := v.ParseTest(writerBody)
	if err := v.CompileTest(ctx, "src/foo.rs", crate["src/foo.rs"], test); err != nil {
		t.Fatalf("the landed test does not compile under %q: %v", testCmd, err)
	}
	mutant := adequacy.Mutant{ID: "m1", Search: "x * 2", Replace: "x + x * 0 + x"}
	broken := adequacy.Mutant{ID: "m2", Search: "x * 2", Replace: "x * 3"}
	rep, err := s.ScoreAuthoredReport(ctx, "src/foo.rs", crate["src/foo.rs"], test, []adequacy.Mutant{broken, mutant}, testCmd)
	if err != nil {
		t.Fatalf("ScoreAuthoredReport under %q: %v", testCmd, err)
	}
	if !rep.CompliantPass || !rep.CanaryKilled || rep.AuthoredTestUnreached {
		t.Fatalf("under %q the authored test did not grade soundly: %+v", testCmd, rep)
	}
	killed := map[string]bool{}
	for _, id := range rep.Killed {
		killed[id] = true
	}
	// m2 (x*3) is a real fault the landed test catches through the private
	// fn; m1 is an equivalent mutant (x + 0 + x == 2x) that nothing can kill.
	if !killed["m2"] || killed["m1"] {
		t.Fatalf("under %q killed = %v, want exactly m2 — the landed test reached private_double", testCmd, rep.Killed)
	}
}

// TestDeclaredLandingGradesInTheJail: in corral's own bwrap jail, offline.
func TestDeclaredLandingGradesInTheJail(t *testing.T) {
	rustToolchainOrSkip(t)
	backend, err := sandbox.Resolve(sandbox.Config{Backend: "bwrap"})
	if err != nil {
		t.Skipf("SKIP: no bwrap here: %v", err)
	}
	landing := landingFor(t, writeCrate(t))
	jail := adequacy.NewJail(backend, 180*time.Second)
	for _, cmd := range []string{"cargo test", "cargo nextest run"} {
		t.Run(strings.ReplaceAll(cmd, " ", "_"), func(t *testing.T) {
			base := make(map[string]string, len(crate))
			for k, v := range crate {
				base[k] = v
			}
			gradeTheLanding(t, jail, base, landing, cmd)
		})
	}
}

// TestDeclaredLandingGradesOnTheWorkspaceSubstrate: the substrate Warp's
// acceptance runs on — BaseFiles EMPTY, the crate on disk — so the composed
// test file must come from the carried Existing, and every write into the
// real *_tests.rs is journaled and restored: both files are byte-identical
// afterwards.
func TestDeclaredLandingGradesOnTheWorkspaceSubstrate(t *testing.T) {
	rustToolchainOrSkip(t)
	dir := writeCrate(t)
	landing := landingFor(t, dir)
	runner := adequacy.NewWorkspaceRunner(dir, 180*time.Second)
	for _, cmd := range []string{"cargo test", "cargo nextest run"} {
		t.Run(strings.ReplaceAll(cmd, " ", "_"), func(t *testing.T) {
			gradeTheLanding(t, runner, map[string]string{}, landing, cmd)
			for _, rel := range []string{"src/foo.rs", "src/foo_tests.rs"} {
				got, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel))) // #nosec G304 -- this test's own temp crate
				if err != nil {
					t.Fatal(err)
				}
				if string(got) != crate[rel] {
					t.Errorf("%s was left changed on the checkout:\n%s", rel, got)
				}
			}
		})
	}
}
