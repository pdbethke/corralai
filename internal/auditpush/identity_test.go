// The audited party, from the checkout: author and committer by name, the
// Co-authored-by trailers by name, never an address; a checkout that cannot
// say records nothing.
func TestCommitIdentityNamesThePartyWithoutAddresses(t *testing.T) {
	dir := t.TempDir()
	run := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=Ada Writer", "GIT_AUTHOR_EMAIL=ada@example.test",
			"GIT_COMMITTER_NAME=Forge Bot", "GIT_COMMITTER_EMAIL=bot@example.test")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v: %s", args, err, out)
		}
	}
	run("init", "-q")
	if err := os.WriteFile(filepath.Join(dir, "a.txt"), []byte("a\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	run("add", ".")
	run("commit", "-q", "--no-gpg-sign", "-m", "change\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-authored-by: Claude Code <noreply@anthropic.com>\nCo-authored-by: <onlyaddr@example.test>\nCo-authored-by: Codex\nCo-authored-by: Ada Writer <ada@example.test>\nCo-authored-by: claude code <x@y>")
	out, _ := exec.Command("git", "-C", dir, "rev-parse", "HEAD").Output()
	sha := strings.TrimSpace(string(out))

	id := CommitIdentity(dir, sha)
	if id.Author != "Ada Writer" || id.Committer != "Forge Bot" {
		t.Fatalf("author/committer: %+v", id)
	}
	// The author repeated as a trailer, and a trailer repeated, fold: one
	// party is named once.
	if got := strings.Join(id.CoAuthorList(), "|"); got != "Claude Code|onlyaddr|Codex" {
		t.Fatalf("co-authors: %q", got)
	}
	if strings.Contains(id.CoAuthors, "@") {
		t.Fatalf("an address leaked: %q", id.CoAuthors)
	}
	// The footer line, read from the same commit, beside the trailers.
	if id.GeneratedWith != "Claude Code" {
		t.Fatalf("generated with: %q", id.GeneratedWith)
	}
	if !CommitIdentity(t.TempDir(), sha).IsZero() || !CommitIdentity(dir, "").IsZero() {
		t.Fatal("a checkout that cannot say must record nothing")
	}
}

// A footer line names the tool it declares, as a link's text or as a few
// plain words; prose that happens to begin the same way names nothing.
func TestGeneratedWithReadsOnlyFooterDeclarations(t *testing.T) {
	msg := strings.Join([]string{
		"Make the parser stricter.",
		"",
		"Generated with care, this change touches three files.",
		"The fixtures were generated with a script we no longer keep.",
		"Generated by the build: do not edit.",
		"",
		"🤖 Generated with [Claude Code](https://claude.com/claude-code)",
		"Generated with Some Tool 2.1",
		"Generated by aider.",
		"generated with Claude Code",
		"🤖 Generated with [claude code](https://example.test/)",
	}, "\n")
	got := strings.Join(generatedWith(msg), "|")
	if got != "Claude Code|Some Tool 2.1|aider" {
		t.Errorf("generatedWith = %q", got)
	}
	if got := generatedWith("Fix a bug.\n\nCo-authored-by: Codex"); got != nil {
		t.Errorf("a message with no footer line named %q", got)
	}
}

// The party rides the scan row through the ledger, the view and a read-back.
func TestScanRowCarriesThePartyThroughTheLedgerAndTheView(t *testing.T) {
	dir := t.TempDir() + "/"
	b := Bundle{Scan: ScanRow{Repo: "o/r", ScanID: 3, Commit: "deadbeef", Host: "h",
		Identity: Identity{Author: "Ada Writer", Committer: "Forge Bot", CoAuthors: "Claude Code\nCodex", GeneratedWith: "Claude Code"}}}
	if _, err := PushBundle(dir, b); err != nil {
		t.Fatal(err)
	}
	entries, _ := ReadLedgerDir(dir)
	if entries[0].Bundle.Scan.Identity != b.Scan.Identity {
		t.Fatalf("entry: %+v", entries[0].Bundle.Scan.Identity)
	}
	db, err := LoadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	rb, err := ReadBundle(db, "o/r", 3)
	if err != nil {
		t.Fatal(err)
	}
	if rb.Scan.Identity != b.Scan.Identity {
		t.Fatalf("view: %+v", rb.Scan.Identity)
	}
	var n int
	if err := db.QueryRow(`SELECT count(*) FROM (SELECT unnest(string_split(co_authors, chr(10))) AS who FROM corral_scans) WHERE who = 'Claude Code'`).Scan(&n); err != nil || n != 1 {
		t.Fatalf("co_authors is one name per line for SQL: %d %v", n, err)
	}
	if err := db.QueryRow(`SELECT count(*) FROM corral_scans WHERE generated_with = 'Claude Code'`).Scan(&n); err != nil || n != 1 {
		t.Fatalf("generated_with reaches the view: %d %v", n, err)
	}
}

// A review's party reaches the reviews view too, footer tools included.
func TestReviewRowCarriesTheToolsTheCommitDeclared(t *testing.T) {
	dir := t.TempDir()
	if _, err := WriteReview(dir, review.Review{Repo: "o/r", Commit: "c" + strings.Repeat("0", 11), Scope: "s", ReviewerModel: "m",
		Author: "Ada Writer", CoAuthors: "Codex", GeneratedWith: "Claude Code", Sound: []string{"a"}}, nil); err != nil {
		t.Fatal(err)
	}
	db, err := LoadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	var got string
	if err := db.QueryRow(`SELECT generated_with FROM corral_reviews`).Scan(&got); err != nil || got != "Claude Code" {
		t.Fatalf("corral_reviews.generated_with = %q, %v", got, err)
	}
}
