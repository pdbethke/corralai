// Command langsupport prints the language-support page from the runner table
// and the parity list the code dispatches on (internal/lang/runner.go,
// internal/lang/parity.go). Internal build tooling: run it through
// scripts/gen-language-support.sh, which writes and drift-checks the page.
package main

import (
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/pdbethke/corralai/internal/lang"
)

func main() {
	site := flag.Bool("site", false, "prefix Starlight frontmatter for the site's copy")
	flag.Parse()
	if _, err := os.Stdout.WriteString(render(*site)); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// render is the page: the site's copy carries Starlight frontmatter in place
// of the repo copy's heading.
func render(site bool) string {
	var b strings.Builder
	if site {
		b.WriteString("---\ntitle: Language support\ndescription: Generated from the runner table corral dispatches on — never hand-written; see scripts/gen-language-support.sh.\n---\n\n")
	} else {
		b.WriteString("# Language support\n\n")
	}
	b.WriteString("> Generated by `scripts/gen-language-support.sh` from `internal/lang/runner.go` and `internal/lang/parity.go`. Do not hand-edit.\n\n")
	b.WriteString("What corral does with each language's tests. This page is rendered from the same table the code dispatches on, so it cannot list a capability the code lacks, and every gap carries the reason the code gives for it.\n\n")

	names := lang.Names()
	b.WriteString("## By language\n\n| | " + strings.Join(names, " | ") + " |\n|---" + strings.Repeat("|---", len(names)) + "|\n")
	reason := map[[2]string]string{}
	for _, e := range lang.ParityExemptions {
		reason[[2]string{e.Lang, e.Capability}] = e.Reason
	}
	var notes []string
	noteOf := map[string]int{}
	for _, c := range lang.Capabilities {
		row := []string{c.Title}
		for _, n := range names {
			p, _ := lang.ByName(n)
			if c.Has(p) {
				row = append(row, "✓"+viaRunners(c, p))
				continue
			}
			r := reason[[2]string{n, c.Key}]
			if _, ok := noteOf[r]; !ok {
				notes = append(notes, r)
				noteOf[r] = len(notes)
			}
			row = append(row, fmt.Sprintf("— (%d)", noteOf[r]))
		}
		b.WriteString("| " + strings.Join(row, " | ") + " |\n")
	}
	b.WriteString("\n")
	for i, r := range notes {
		fmt.Fprintf(&b, "%d. %s\n", i+1, r)
	}

	b.WriteString("\n## By runner\n\nA language has a runner capability when any of its runners does; this is which. corral recognises the runner from the test command you pass, or from the package script it runs: ")
	var via []string
	for _, l := range lang.ScriptLaunchers() {
		pass := "directly"
		if l.Pass != "" {
			pass = "after `" + l.Pass + "`"
		}
		via = append(via, fmt.Sprintf("`%s` reads `%s` and hands the runner its arguments %s", l.Name, l.Manifest, pass))
	}
	b.WriteString(strings.Join(via, "; ") + ". A script gets the runner's arguments only when it is one command, since a launcher appends them to the end of the script. `--runner <id>` names the runner when corral cannot read it. A command whose runner corral does not know (a `make` target) is graded exactly the same, by exit code, as its language's default runner, except that it never gets a fail-fast flag.\n\n")
	b.WriteString("| runner | `--runner` | languages | stop at first failure | list tests | run one test | names the killing test | salvage | names flaky tests | note |\n|---|---|---|---|---|---|---|---|---|---|\n")
	mark := func(ok bool) string {
		if ok {
			return "✓"
		}
		return ""
	}
	for _, r := range lang.Runners() {
		name := "`" + r.Name + "`"
		if r.Default {
			name += " (default)"
		}
		ff := ""
		if len(r.FailFast) > 0 {
			ff = "`" + strings.Join(r.FailFast, " ") + "`"
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s | %s | %s | %s | %s |\n", name, r.ID, strings.Join(r.Languages, ", "), ff,
			mark(r.ListCmd != nil && r.ParseList != nil), mark(r.SingleCmd != nil), mark(r.FirstFailure != nil),
			mark(r.FailedTests != nil && r.DeselectArgs != nil), mark(r.Flaky != nil), r.Note)
	}
	return b.String()
}

// viaRunners names the rows that give p capability c when p's stock command
// does not get it as is, as " (jest, mocha)"; "" otherwise.
func viaRunners(c lang.Capability, p lang.Plugin) string {
	if c.Row == nil || c.Stock(p) {
		return ""
	}
	var names []string
	for _, r := range lang.Runners() {
		if slices.Contains(r.Languages, p.Name()) && c.Row(r) {
			names = append(names, r.Name)
		}
	}
	return " (" + strings.Join(names, ", ") + ")"
}
