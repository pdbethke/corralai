// Command recordfields prints the record-fields page from the tier table
// (internal/ledger/tiers.go). Internal build tooling: run it through
// scripts/gen-record-fields.sh, which writes and drift-checks the page.
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/pdbethke/corralai/internal/ledger"
)

func main() {
	if _, err := os.Stdout.WriteString(render()); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// cell keeps a Note from breaking a Markdown table row.
func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

func render() string {
	var b strings.Builder
	b.WriteString("# What each field in the record can be trusted for\n\n")
	b.WriteString("> Generated by `scripts/gen-record-fields.sh` from `internal/ledger/tiers.go`. Do not hand-edit.\n\n")
	b.WriteString("Signing proves integrity and authorship of the record, not truth of its contents. Every field corral records carries one of four tiers, which says what it can be trusted for.\n\n")
	b.WriteString("- **measured**: what corral itself set, observed or executed: counts, durations, timestamps, settings, versions, the model and seat each role ran on, and the outcome of anything it ran. A kill rate, a survivor, the source of a test that ran.\n")
	b.WriteString("- **declared**: what the audited commit or a person says: a commit's author, committer, Co-authored-by trailers and the tools named in a \"Generated with\" footer, and a person's adjudication, retraction or signer-change reason. The audited party writes a commit's names freely, or removes them, so read them as metrics about a change and never as evidence of who or what wrote it; a person's words are theirs and are not verified as true.\n")
	b.WriteString("- **meta**: the run's narrative and notes about itself (its event kinds, actors, subjects and detail, its free-text notes) and a model's opinion. Signed, but forgeable by the key holder, and never verified as true.\n")
	b.WriteString("- **key**: names or links and measures nothing: repo, commit, ids, hashes, the run URL, signatures, the previous-entry link.\n\n")
	b.WriteString("The table is checked against the record's Go types by a test, so a field cannot be added to the record without a tier being decided for it.\n")

	rows := ledger.FieldTiers()
	for i, ft := range rows {
		if i == 0 || rows[i-1].Row != ft.Row {
			fmt.Fprintf(&b, "\n## %s\n\n| Field | Tier | Note |\n|---|---|---|\n", ft.Row)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", ft.Field, ft.Tier, cell(ft.Note))
	}
	return b.String()
}
